import uuid
from datetime import date

from fastapi import APIRouter, Depends, Query
from fastapi.responses import Response
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.core.database import get_db
from app.core.dependencies import get_current_user, require_roles
from app.core.exceptions import AppError
from app.core.enums import InvoiceStatus
from app.core.pagination import paginate
from app.modules.accounts.models import User, UserRole
from app.modules.customers.service import scope_customer_id
from app.modules.invoices import service
from app.modules.invoices.models import Invoice
from app.modules.invoices.pdf import render_invoice_pdf
from app.modules.invoices.schemas import BulkInvoiceIn, BulkInvoiceOut, InvoiceIn, InvoiceOut
from app.schemas.common import ApiResponse, ErrorResponse, Page, PageParams

router = APIRouter(prefix="/invoices", tags=["invoices"])
_errors = {401: {"model": ErrorResponse}, 403: {"model": ErrorResponse}, 404: {"model": ErrorResponse}, 409: {"model": ErrorResponse}}
_staff = require_roles(UserRole.ADMIN, UserRole.STAFF)
_SORTS = {"created_at": Invoice.created_at, "issue_date": Invoice.issue_date, "due_date": Invoice.due_date, "total": Invoice.total, "number": Invoice.number}


@router.get("/", response_model=ApiResponse[Page[InvoiceOut]], responses=_errors)
def list_invoices(page: PageParams = Depends(), q: str | None = Query(None, max_length=100), status: InvoiceStatus | None = None,
                  overdue: bool | None = None, payable: bool | None = None, customer_id: uuid.UUID | None = None, subscription_id: uuid.UUID | None = None,
                  date_from: date | None = None, date_to: date | None = None, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    stmt = select(Invoice)
    scope = scope_customer_id(db, user)
    if scope is not None:  # customers: own invoices, never drafts
        stmt = stmt.where(Invoice.customer_id == scope, Invoice.status != InvoiceStatus.DRAFT)
    elif customer_id:
        stmt = stmt.where(Invoice.customer_id == customer_id)
    if q:
        stmt = stmt.where(func.lower(Invoice.number).like(f"%{q.lower()}%"))
    if status:
        stmt = stmt.where(Invoice.status == status)
    if subscription_id:
        stmt = stmt.where(Invoice.subscription_id == subscription_id)
    if date_from:
        stmt = stmt.where(Invoice.issue_date >= date_from)
    if date_to:
        stmt = stmt.where(Invoice.issue_date <= date_to)
    if payable:
        stmt = stmt.where(Invoice.status.in_(service.PAYABLE), Invoice.total - Invoice.amount_paid > 0)
    if overdue is not None:
        cond = (Invoice.status.in_(service.PAYABLE)) & (Invoice.due_date < date.today()) & (Invoice.total - Invoice.amount_paid > 0)
        stmt = stmt.where(cond if overdue else ~cond)
    return ApiResponse(data=paginate(db, stmt, page, InvoiceOut, _SORTS, "-created_at"))


@router.post("/", status_code=201, response_model=ApiResponse[InvoiceOut], responses=_errors)
def create_invoice(body: InvoiceIn, db: Session = Depends(get_db), actor: User = Depends(_staff)):
    """Manual invoice (draft). Recurring invoices are generated by the billing engine."""
    inv = service.create_manual(db, body, actor)
    db.commit()
    return ApiResponse(message="Invoice created", data=InvoiceOut.model_validate(inv))


@router.get("/{invoice_id}/", response_model=ApiResponse[InvoiceOut], responses=_errors)
def get_invoice(invoice_id: uuid.UUID, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    return ApiResponse(data=InvoiceOut.model_validate(service.get_invoice(db, user, invoice_id)))


@router.post("/bulk-confirm/", response_model=ApiResponse[BulkInvoiceOut], responses=_errors)
def bulk_confirm(body: BulkInvoiceIn, db: Session = Depends(get_db), actor: User = Depends(_staff)):
    """Confirms (and optionally sends) many invoices; one failure never blocks the rest."""
    confirmed = sent = 0
    skipped: list[dict] = []
    for iid in dict.fromkeys(body.ids):
        try:
            inv = service.get_invoice(db, actor, iid, lock=True)
            if inv.status == InvoiceStatus.DRAFT:
                service.confirm(db, inv, actor)
                confirmed += 1
            if body.send:
                service.send(db, inv, actor)
                sent += 1
            db.commit()
        except AppError as e:
            db.rollback()
            skipped.append({"id": str(iid), "reason": e.message})
    return ApiResponse(message=f"{confirmed} confirmed, {sent} sent", data=BulkInvoiceOut(confirmed=confirmed, sent=sent, skipped=skipped))


