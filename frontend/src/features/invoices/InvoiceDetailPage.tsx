import { useQuery } from '@tanstack/react-query'
import { useState } from 'react'
import { useParams } from 'react-router-dom'
import { PageContainer } from '@/components/layout/PageContainer'
import { ConfirmationDialog } from '@/components/shared/ConfirmationDialog'
import { ErrorState } from '@/components/shared/ErrorState'
import { LoadingState } from '@/components/shared/LoadingState'
import { PageHeader } from '@/components/shared/PageHeader'
import { QueryTable } from '@/components/shared/QueryTable'
import { Section } from '@/components/shared/Section'
import { StatusBadge } from '@/components/shared/StatusBadge'
import { Button } from '@/components/ui/button'
import { useApiMutation } from '@/hooks/useApiMutation'
import { useListQuery } from '@/hooks/useListQuery'
import { dateTime, label, money } from '@/lib/format'
import { queryKeys } from '@/lib/queryKeys'
import { invoiceService } from '@/services/invoice.service'
import { paymentService } from '@/services/payment.service'
import { RecordPaymentDialog } from '@/features/payments/RecordPaymentDialog'
import { InvoiceView } from './InvoiceView'
import { invoiceStatus } from './InvoicesPage'

export default function InvoiceDetailPage() {
  const { id = '' } = useParams()
  const [confirm, setConfirm] = useState<'confirm' | 'cancel' | null>(null)
  const [paying, setPaying] = useState(false)
  const query = useQuery({ queryKey: queryKeys.invoices.detail(id), queryFn: () => invoiceService.get(id) })
  const payments = useListQuery(queryKeys.payments.list, paymentService.list, { invoice_id: id, page_size: 50 })
  const act = useApiMutation((a: 'confirm' | 'cancel' | 'send') => invoiceService.action(id, a), { invalidate: [queryKeys.invoices.all], success: (_, a) => ({ confirm: 'Invoice confirmed', cancel: 'Invoice cancelled', send: 'Invoice sent to the customer' })[a], onSuccess: () => setConfirm(null) })
  const pdf = useApiMutation((open: boolean) => invoiceService.pdf(query.data!, open))

  const i = query.data
  if (query.isLoading) return <PageContainer><LoadingState /></PageContainer>
  if (!i) return <PageContainer><ErrorState message={query.error?.message} onRetry={() => query.refetch()} /></PageContainer>
  const payable = i.status === 'CONFIRMED' || i.status === 'PARTIALLY_PAID'
  return (
    <PageContainer>
      <PageHeader title={i.number} description={`${i.source === 'AUTO' ? 'Generated by billing' : 'Manual invoice'} · ${i.currency}`} actions={<>
        <StatusBadge status={invoiceStatus(i)} />
        {i.status === 'DRAFT' && <Button size="sm" onClick={() => setConfirm('confirm')}>Confirm</Button>}
        {payable && <Button size="sm" onClick={() => setPaying(true)}>Record payment</Button>}
        {(i.status === 'CONFIRMED' || i.status === 'PARTIALLY_PAID' || i.status === 'PAID') && <Button size="sm" variant="outline" onClick={() => act.mutate('send')}>Send</Button>}
        <Button size="sm" variant="outline" onClick={() => pdf.mutate(false)}>Download PDF</Button>
        <Button size="sm" variant="outline" onClick={() => pdf.mutate(true)}>Print</Button>
        {(i.status === 'DRAFT' || (i.status === 'CONFIRMED' && Number(i.amount_paid) === 0)) && <Button size="sm" variant="destructive" onClick={() => setConfirm('cancel')}>Cancel invoice</Button>}
      </>} />
      <InvoiceView invoice={i}>
        <Section title="Payments" flush>
          <QueryTable bare query={payments} page={1} onPage={() => undefined} rowKey={(p) => p.id} emptyTitle="No payments yet" columns={[
            { header: 'Date', cell: (p) => dateTime(p.payment_date ?? p.created_at) }, { header: 'Method', cell: (p) => label(p.method) }, { header: 'Amount', cell: (p) => money(p.amount) },
            { header: 'Status', cell: (p) => <StatusBadge status={p.status} /> }, { header: 'Reference', cell: (p) => p.transaction_reference ?? '-' }]} />
        </Section>
      </InvoiceView>
      <RecordPaymentDialog open={paying} invoice={i} onClose={() => setPaying(false)} />
      {confirm && <ConfirmationDialog open destructive={confirm === 'cancel'} title={confirm === 'confirm' ? 'Confirm this invoice?' : 'Cancel this invoice?'} confirmLabel={confirm === 'confirm' ? 'Confirm' : 'Cancel invoice'}
        description={confirm === 'confirm' ? 'The customer will see it and can pay it.' : 'Cancelled invoices keep their record but can no longer be paid. A recurring invoice\'s period is not billed again.'} onConfirm={() => act.mutate(confirm)} onCancel={() => setConfirm(null)} />}
    </PageContainer>
  )
}
